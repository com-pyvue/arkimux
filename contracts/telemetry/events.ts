import { z } from "zod";

// This module is the only shareable boundary. No AWS or Local runtime imports.
export const usageKinds = [
  "arkimux.event.consent.success",
  "arkimux.event.local.start",
  "arkimux.event.connection.create.success",
  "arkimux.event.connection.test.start",
  "arkimux.event.connection.test.success",
  "arkimux.event.connection.test.error",
  "arkimux.event.configuration.save.success",
  "arkimux.event.run.start",
  "arkimux.event.run.success",
  "arkimux.event.run.error",
  "arkimux.event.run.cancel",
  "arkimux.event.run_result.fetch.success",
] as const;

export const uuid = z.string().uuid().regex(/^[0-9a-f-]+$/);
// Cognito sub uses a GUID shape but does not guarantee RFC UUID variant bits.
export const installationId = z.string().regex(/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/);
const isoTime = z.string().datetime({ precision: 3 }).refine(value => {
  try { return new Date(value).toISOString() === value; } catch { return false; }
});
const version = z.string().regex(/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/).max(80);
const base = {
  schema_version: z.literal(1),
  event_id: uuid,
  installation_id: installationId,
  consent_journey_id: uuid,
  event_time: isoTime,
  send_time: isoTime,
  arkimux_version: version,
};

export const usageEventSchema = z.strictObject({
  ...base,
  kind: z.enum(usageKinds),
  operation_id: uuid.optional(),
}).superRefine((event, context) => {
  const needsOperation = !["arkimux.event.consent.success", "arkimux.event.local.start"].includes(event.kind);
  if (needsOperation !== (event.operation_id !== undefined)) {
    context.addIssue({ code: "custom", path: ["operation_id"], message: "Invalid operation correlation." });
  }
});

export type UsageEvent = z.infer<typeof usageEventSchema>;
export interface IngestionLimits {
  maxBodyBytes: number;
  maxBatchEvents: number;
}

export function validateLimits(limits: IngestionLimits): void {
  for (const key of ["maxBodyBytes", "maxBatchEvents"] as const) {
    const value = limits[key];
    if (!Number.isSafeInteger(value) || value < 1) throw new Error("Invalid telemetry limits.");
  }
  // Hard transport ceilings, not production admission/quota defaults.
  if (limits.maxBodyBytes > 128 * 1024 || limits.maxBatchEvents > 100) {
    throw new Error("Telemetry limits exceed transport ceilings.");
  }
}

export function parseUsageBatch(value: unknown, limits: IngestionLimits): UsageEvent[] {
  validateLimits(limits);
  const { events } = z.strictObject({ events: z.array(usageEventSchema).min(1).max(limits.maxBatchEvents) }).parse(value);
  if (new Set(events.map(event => event.event_id)).size !== events.length) throw new Error("Duplicate event IDs in batch.");
  return events;
}

export const registrationSchema = z.strictObject({
  schema_version: z.literal(1),
  registration_id: uuid,
  // 32 random bytes encoded as unpadded base64url, generated by Local.
  secret: z.string().regex(/^[A-Za-z0-9_-]{43}$/),
});
export type Registration = z.infer<typeof registrationSchema>;

export const deletionRequestSchema = z.strictObject({ schema_version: z.literal(1), confirm: z.literal(true) });
export const deletionReceiptSchema = z.strictObject({ schema_version: z.literal(1), request_id: uuid,
  requested_at: isoTime, status: z.enum(["accepted", "data_removed"]), completion_due_at: isoTime });
export type DeletionReceipt = z.infer<typeof deletionReceiptSchema>;
